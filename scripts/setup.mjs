import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createInterface } from 'node:readline/promises';
import { Writable } from 'node:stream';
import { spawnSync } from 'node:child_process';

export const root = fileURLToPath(new URL('../', import.meta.url));

export function startCommand(output) {
  const path = relative(root, resolve(output)).replaceAll('\\', '/');
  if (path.includes("'"))
    return 'Run docker compose with --env-file set to the configuration path printed above (quoted for your shell), followed by up --build -d --wait.';
  const file = /^[A-Za-z0-9_./-]+$/.test(path) ? path : `'${path}'`;
  return `docker compose${path === '.env' ? '' : ` --env-file ${file}`} up --build -d --wait`;
}

export function validateSettings(settings) {
  const passwordLength = Array.from(settings.password ?? '').length;
  if (!/^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/.test(settings.org))
    throw new Error(
      'Organization must be a lowercase URL slug, for example my-company (maximum 63 characters).',
    );
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(settings.email) || settings.email.length > 254)
    throw new Error('Enter a valid administrator email address.');
  if (!/^[a-z0-9][a-z0-9._-]{0,63}$/.test(settings.team))
    throw new Error('Enter a valid team slug.');
  for (const key of ['port', 'apiPort']) {
    if (!Number.isInteger(settings[key]) || settings[key] < 1024 || settings[key] > 65535)
      throw new Error('Local ports must be integers between 1024 and 65535.');
  }
  if (settings.port === settings.apiPort) throw new Error('Dashboard and API ports must differ.');
  if (passwordLength < 12 || passwordLength > 128 || /[\r\n]/.test(settings.password))
    throw new Error('Administrator password must contain 12–128 characters on one line.');
}

export function collectorConfig() {
  const template = readFileSync(
    resolve(root, 'infra/charts/observability/templates/collector-config.yaml'),
    'utf8',
  );
  const content = template.split('  config.yaml: |')[1];
  if (!content || content.includes('{{'))
    throw new Error('Collector template requires an updated setup renderer.');
  return content
    .replace(/^\r?\n/, '')
    .split(/\r?\n/)
    .map((line) => line.replace(/^ {4}/, ''))
    .join('\n');
}

export async function environmentFor(settings) {
  validateSettings(settings);
  const { hashPassword } = await import('../apps/backend/src/modules/auth/password.ts');
  return {
    HUB_PORT: String(settings.port),
    API_PORT: String(settings.apiPort),
    HUB_PUBLIC_URL: `http://localhost:${settings.port}`,
    AUTH_JWT_SECRET: randomBytes(48).toString('base64url'),
    INGESTION_COLLECTOR_TOKEN: randomBytes(32).toString('base64url'),
    AUTH_USERS_JSON: JSON.stringify([
      {
        tenantSlug: settings.org,
        email: settings.email.trim().toLowerCase(),
        role: 'admin',
        teams: [settings.team],
        passwordHash: await hashPassword(settings.password),
      },
    ]),
  };
}

function saveCollector(configuration = resolve(root, '.local/collector.yaml')) {
  mkdirSync(dirname(configuration), { recursive: true });
  writeFileSync(
    configuration,
    '# Generated from the Helm Collector template by setup.mjs.\n' + collectorConfig(),
    { mode: 0o644 },
  );
}

export async function saveSetup(
  settings,
  output = resolve(root, '.env'),
  configuration = resolve(root, '.local/collector.yaml'),
) {
  if (existsSync(output)) throw new Error('Configuration already exists; nothing was overwritten.');
  const values = await environmentFor(settings);
  saveCollector(configuration);
  mkdirSync(dirname(output), { recursive: true });
  const text =
    '# Generated by scripts/setup.mjs. Local secrets: do not commit or share.\n' +
    Object.entries(values)
      .map(([key, value]) => `${key}='${value.replaceAll("'", "\\'")}'`)
      .join('\n') +
    '\n';
  writeFileSync(output, text, { mode: 0o600, flag: 'wx' });
}

function options(args) {
  const values = {
    org: 'demo',
    team: 'backend',
    port: 5000,
    apiPort: 3001,
    output: resolve(root, '.env'),
  };
  const names = {
    '--org': 'org',
    '--email': 'email',
    '--team': 'team',
    '--port': 'port',
    '--api-port': 'apiPort',
    '--output': 'output',
  };
  for (let index = 0; index < args.length; index++) {
    if (args[index] === '--password-stdin') {
      values.passwordStdin = true;
      continue;
    }
    const key = names[args[index]];
    if (!key || !args[index + 1] || args[index + 1].startsWith('--'))
      throw new Error('Unknown or incomplete option. Run node scripts/setup.mjs --help.');
    const value = args[++index];
    values[key] = ['port', 'apiPort'].includes(key) ? Number(value) : value;
  }
  values.output = resolve(values.output);
  return values;
}

export function checkDocker(run = spawnSync) {
  for (const args of [
    ['compose', 'version'],
    ['info', '--format', '{{.OSType}}'],
  ]) {
    const result = run('docker', args, { encoding: 'utf8', windowsHide: true });
    if (result.error || result.status !== 0)
      throw new Error(
        'Docker with Compose is not ready. Install/start Docker Desktop (Linux containers), then rerun setup.',
      );
    if (args[0] === 'info' && result.stdout.trim() !== 'linux')
      throw new Error('Switch Docker Desktop to Linux containers, then rerun setup.');
  }
}

async function passwordFromStdin() {
  let input = '';
  for await (const chunk of process.stdin) input += chunk;
  return input.replace(/\r?\n$/, '');
}

function terminal() {
  let muted = false;
  const output = new Writable({
    write(chunk, encoding, done) {
      if (!muted) process.stdout.write(chunk, encoding);
      done();
    },
  });
  output.isTTY = true;
  const rl = createInterface({ input: process.stdin, output, terminal: true, historySize: 0 });
  const controller = new AbortController();
  rl.on('SIGINT', () => controller.abort());
  const ask = async (label, secret = false) => {
    const answer = rl.question(label, { signal: controller.signal });
    muted = secret;
    try {
      return await answer;
    } finally {
      muted = false;
      if (secret) process.stdout.write('\n');
    }
  };
  return { ask, close: () => rl.close() };
}

async function interactive(settings) {
  if (!process.stdin.isTTY || !process.stdout.isTTY)
    throw new Error('Use an interactive terminal, or --password-stdin with --email and --org.');
  const prompt = terminal();
  try {
    settings.org =
      (await prompt.ask(`Organization URL slug [${settings.org}]: `)).trim() || settings.org;
    settings.email =
      (
        await prompt.ask(`Administrator email${settings.email ? ` [${settings.email}]` : ''}: `)
      ).trim() || settings.email;
    settings.team = (await prompt.ask(`First team [${settings.team}]: `)).trim() || settings.team;
    settings.password = await prompt.ask(
      'Choose administrator password (12–128 characters, hidden): ',
      true,
    );
    if (settings.password !== (await prompt.ask('Confirm password (hidden): ', true)))
      throw new Error('Passwords did not match. Rerun setup; nothing was saved.');
    return settings;
  } finally {
    prompt.close();
  }
}

async function main() {
  if (process.argv.includes('--help')) {
    console.log(
      'Usage: node scripts/setup.mjs [--org SLUG] [--email EMAIL] [--team SLUG] [--port 5000] [--api-port 3001]\nAutomation: add --password-stdin; optional --output PATH. Existing files are never overwritten.',
    );
    return;
  }
  if (Number(process.versions.node.split('.')[0]) < 24)
    throw new Error('Install Node.js 24 or newer, then rerun setup.');
  const settings = options(process.argv.slice(2));
  if (existsSync(settings.output)) {
    saveCollector();
    console.log(
      `Existing ${settings.output} preserved. Setup does not reset accounts.\nRun: ${startCommand(settings.output)}`,
    );
    return;
  }
  checkDocker();
  console.log(
    'Telemetry Hub — local setup\nThis creates your first administrator and generates private local secrets.',
  );
  if (settings.passwordStdin) settings.password = await passwordFromStdin();
  else await interactive(settings);
  await saveSetup(settings, settings.output);
  console.log(
    `\nSetup saved to ${settings.output}\nOrganization: ${settings.org}\nEmail: ${settings.email.trim().toLowerCase()}\nYour password was not saved in plaintext.\n\nNext: ${startCommand(settings.output)}\nOpen: http://localhost:${settings.port}\nIngestion endpoint: http://localhost:${settings.apiPort}/api/ingest\nSign in with the organization, email and password you just chose.\nUse Administration to add users and generate ingestion keys.`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.name === 'AbortError' ? 'Setup cancelled.' : error.message);
    process.exitCode = 1;
  });
}
